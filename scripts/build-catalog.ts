/**
 * Builds src/lib/catalog.generated.ts from a checkout of congminh1254/shopee-sdk.
 *
 * The catalog maps every SDK manager method to its Shopee endpoint, HTTP method,
 * auth requirement and (trimmed) request/response field docs from the spec files.
 *
 * Usage: npm run gen:catalog -- ../shopee-sdk
 */
import fs from "node:fs";
import path from "node:path";
import type { CatalogEntry, CatalogParam } from "../src/lib/catalog-types";

type SpecParam = {
  name: string;
  type: string;
  required?: string;
  description?: string;
  children?: SpecParam[];
};

const sdkRoot = path.resolve(process.argv[2] ?? "../shopee-sdk");
const managersDir = path.join(sdkRoot, "src/managers");
const schemasDir = path.join(sdkRoot, "schemas");
const outFile = path.resolve("src/lib/catalog.generated.ts");

const READ_PREFIXES = ["get_", "search_", "check_", "query_", "list_", "view_", "download_"];

function stripHtml(s: unknown): string {
  return (typeof s === "string" ? s : "")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function truncate(s: string, n: number): string {
  return s.length > n ? `${s.slice(0, n - 1)}…` : s;
}

function convertParams(params: SpecParam[] | undefined, depth: number): CatalogParam[] {
  return (params ?? []).map((p) => {
    const out: CatalogParam = {
      name: p.name,
      type: p.type,
      required: String(p.required).toLowerCase() === "true",
      description: truncate(stripHtml(p.description), 300),
    };
    if (p.children?.length && depth > 0) {
      out.children = convertParams(p.children, depth - 1);
    }
    return out;
  });
}

function camelCase(s: string): string {
  return s.replace(/[-_](\w)/g, (_, c: string) => c.toUpperCase());
}

// Index spec files by API path, e.g. "/order/get_order_list".
const specs = new Map<string, any>();
for (const file of fs.readdirSync(schemasDir)) {
  if (!file.endsWith(".json")) continue;
  const spec = JSON.parse(fs.readFileSync(path.join(schemasDir, file), "utf8"));
  if (typeof spec.path === "string") {
    specs.set(spec.path.replace(/^\/api\/v2/, ""), spec);
  }
}

const methodRe =
  /public async (\w+)\([\s\S]*?ShopeeFetch\.fetch<[\s\S]*?>\(\s*this\.config,\s*"([^"]+)",\s*\{([\s\S]*?)\}\s*\)/g;

const entries: CatalogEntry[] = [];
for (const file of fs.readdirSync(managersDir).sort()) {
  if (!file.endsWith(".manager.ts") || file === "base.manager.ts") continue;
  const sdkProperty = camelCase(file.replace(".manager.ts", ""));
  const source = fs.readFileSync(path.join(managersDir, file), "utf8");
  for (const m of source.matchAll(methodRe)) {
    const [, sdkMethod, apiPath, opts] = m;
    const httpMethod = /method:\s*"POST"/.test(opts) ? "POST" : "GET";
    const auth = /auth:\s*true/.test(opts);
    const [, module, name] = apiPath.split("/");
    const spec = specs.get(apiPath);
    // Only shop-scoped endpoints are exposed: the SDK signs requests with a shop
    // token, and partner/merchant-level APIs could leak data across tenants.
    if (spec?.api_type !== "Shop" || !auth) continue;
    entries.push({
      id: `${module}.${name}`,
      module,
      sdkProperty,
      sdkMethod,
      httpMethod,
      path: apiPath,
      auth,
      apiType: spec?.api_type ?? "unknown",
      access: READ_PREFIXES.some((p) => name.startsWith(p)) ? "read" : "write",
      description: truncate(stripHtml(spec?.define), 600),
      request: convertParams(spec?.params?.request_params, 4),
      response: convertParams(spec?.params?.response_params, 2),
    });
  }
}

entries.sort((a, b) => a.id.localeCompare(b.id));
// Emitted as a string literal so TypeScript doesn't infer a type for ~1 MB of JSON.
fs.writeFileSync(
  outFile,
  `// NOTE: Generated by scripts/build-catalog.ts. Do not edit directly.\n` +
    `import type { CatalogEntry } from "./catalog-types";\n\n` +
    `export const catalog: CatalogEntry[] = JSON.parse(${JSON.stringify(JSON.stringify(entries))});\n`
);
const byType = entries.reduce<Record<string, number>>((acc, e) => {
  acc[e.apiType] = (acc[e.apiType] ?? 0) + 1;
  return acc;
}, {});
console.log(
  `Wrote ${entries.length} endpoints to ${path.relative(process.cwd(), outFile)}`,
  byType,
  `(${(fs.statSync(outFile).size / 1024).toFixed(0)} KB)`
);
